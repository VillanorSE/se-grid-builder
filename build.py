"""Build SE Grid Builder as one self-contained page.

    python tools/se-grid-builder/build.py [--out <file.html>]

1. armor_data.js <- tools/grid-overlay/armor_shapes.json (the owner-confirmed vanilla armour shapes)
2. se-grid-builder.html <- app.html with core.js, mwm.js, seed.js and armor_data.js inlined (a page opened from disk
   can't load ES modules from neighbouring files), written next to this script unless --out is given.
"""
import argparse
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
SHAPES = HERE.parent / "grid-overlay" / "armor_shapes.json"   # source of armor_data.js, when present


def armor_data():
    shapes = json.loads(SHAPES.read_text(encoding="utf-8"))
    keep = [{k: s[k] for k in ("topology", "key", "name", "block", "pieces", "verts")} for s in shapes]
    js = ("// Generated by build.py from tools/grid-overlay/armor_shapes.json; do not edit.\n"
          "export const ARMOR = " + json.dumps(keep, separators=(",", ":")) + ";\n")
    (HERE / "armor_data.js").write_text(js, encoding="utf-8", newline="\n")
    return len(keep)


def module_body(name):
    src = (HERE / name).read_text(encoding="utf-8")
    src = re.sub(r"^import .*?;\n", "", src, flags=re.M)
    src = re.sub(r"^export (const|function|let|class|async function) ", r"\1 ", src, flags=re.M)
    assert "export " not in re.sub(r"//.*", "", src), name + " still has an export"
    return f"// ---- {name}\n{src}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(HERE / "docs" / "index.html"))
    a = ap.parse_args()
    n = armor_data() if SHAPES.exists() else "committed"
    app = (HERE / "app.html").read_text(encoding="utf-8")
    bundle = "\n".join(module_body(m) for m in ("armor_data.js", "panel_data.js", "core.js", "mwm.js", "seed.js", "importer.js"))
    marker = "/*__MODULES__*/"
    assert app.count(marker) == 1
    out = app.replace(marker, bundle)
    Path(a.out).write_text(out, encoding="utf-8", newline="\n")
    print(f"{n} armour shapes; wrote {a.out} ({len(out) // 1024} KB)")


if __name__ == "__main__":
    import sys
    if len(sys.argv) > 1 and sys.argv[1] == "--data-only":
        print(armor_data(), "armour shapes -> armor_data.js")
    else:
        main()
