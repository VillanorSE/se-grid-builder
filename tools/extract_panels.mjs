// Builds panel_data.js (the vanilla armour panels for the starting Cube Library) from the game's own files:
//   node tools/se-grid-builder/extract_panels.mjs [path to SpaceEngineers/Content]
// One card per panel type (light/heavy and small/large share it); the shape is the small light panel's model.
// Round panels are left out (owner: no round blocks).
import fs from 'fs';
import path from 'path';
import { fileURLToPath, pathToFileURL } from 'url';
const here = path.dirname(fileURLToPath(import.meta.url));
const C = await import(pathToFileURL(path.join(here, 'core.js')));
const { readMwm } = await import(pathToFileURL(path.join(here, 'mwm.js')));

const content = process.argv[2] || 'C:/Program Files (x86)/Steam/steamapps/common/SpaceEngineers/Content';
const texts = C.parseResx(fs.readFileSync(path.join(content, 'Data/Localization/MyTexts.resx'), 'utf8'));
const defs = C.parseBlockDefs(fs.readFileSync(path.join(content, 'Data/CubeBlocks/CubeBlocks_ArmorPanels.sbc'), 'utf8'))
  .filter(d => !/Round/.test(d.subtype) && d.size.every(v => v === 1));
const type = d => d.subtype.replace(/^(Small|Large)/, '').replace(/Light|Heavy/, '');
const groups = new Map();
for (const d of defs) { const t = type(d); if (!groups.has(t)) groups.set(t, []); groups.get(t).push(d); }

// short map keys by panel type (P = panel; C centred, H half, Q quarter, S slope, Sd side, 2 = 2x1, B/T base/tip, R/L)
const KEYS = { ArmorPanel: 'P', ArmorCenterPanel: 'PC', ArmorSlopedSidePanel: 'PSd', ArmorSlopedPanel: 'PS', ArmorHalfPanel: 'PH',
  ArmorHalfCenterPanel: 'PHC', ArmorQuarterPanel: 'PQ', Armor2x1SlopedPanel: 'P2B', Armor2x1SlopedPanelTip: 'P2T',
  Armor2x1SlopedSideBasePanel: 'P2BR', Armor2x1SlopedSideTipPanel: 'P2TR', Armor2x1SlopedSideBasePanelInv: 'P2BL',
  Armor2x1SlopedSideTipPanelInv: 'P2TL', ArmorHalfSlopedPanel: 'PHS', Armor2x1HalfSlopedPanelRight: 'H2BR',
  Armor2x1HalfSlopedTipPanelRight: 'H2TR', Armor2x1HalfSlopedPanelLeft: 'H2BL', Armor2x1HalfSlopedTipPanelLeft: 'H2TL' };
const out = [];
for (const [t, list] of groups) {
  const base = list.find(d => d.cubeSize === 'Small' && /Light/.test(d.subtype));
  if (!base) { console.log('no small light panel for', t); continue; }
  const tris = C.modelToCell(readMwm(fs.readFileSync(path.join(content, base.model.split('\\').join('/')))).tris, base);
  const name = C.blockName(base, texts).replace(/^Light /, '');
  const sh = { plate: true, solids: [{ type: 'tris', tris }] }, m = C.shapeMask(sh);
  // the heavy version should have the same footprint
  const heavy = list.find(d => d.cubeSize === 'Small' && /Heavy/.test(d.subtype));
  let note = '';
  if (heavy) {
    const ht = C.modelToCell(readMwm(fs.readFileSync(path.join(content, heavy.model.split('\\').join('/')))).tris, heavy);
    const hm = C.shapeMask({ plate: true, solids: [{ type: 'tris', tris: ht }] });
    if (C.shapeKeySig(hm.mask) !== C.shapeKeySig(m.mask)) note = 'heavy differs';
  }
  const key = KEYS[t]; if (!key) throw new Error('no key for panel type ' + t);
  out.push({ id: 'panel:' + t, key, name, blocks: list.map(d => ({ subtype: d.subtype, size: d.cubeSize, mod: 'Vanilla', name: C.blockName(d, texts) })),
    tris: Array.from(tris, v => Math.round(v * 1e4) / 1e4) });
  console.log(key.padEnd(5), name.padEnd(36), `${tris.length / 9} tris, ${C.maskCount(m.mask)} samples${m.plate ? ', plate' : ''} ${note}`);
}
fs.writeFileSync(path.join(here, 'panel_data.js'),
  '// Generated by extract_panels.mjs from the game\'s armour panel models; do not edit.\nexport const PANELS = ' + JSON.stringify(out) + ';\n');
console.log(out.length, 'panels -> panel_data.js');
